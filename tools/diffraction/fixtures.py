"""BTM reference for a general rigid wedge (edge = z axis, faces at angle 0 and n*pi of the air sector)."""
import sys, json; import os; sys.path.insert(0,os.path.dirname(__file__))
import numpy as np
from utd import utd_A
C=343.0  # core SPEED_OF_SOUND
FC=np.array([125,250,500,1000,2000,4000.])
def btm_wedge(ps,pl,rs,rr,zs,zr,n,k,Y=25.0):
    nu=1/n
    zc=zs+(zr-zs)*rs/(rs+rr)
    u=np.concatenate([np.geomspace(1e-7,2e-3,400),np.arange(2e-3,Y,1.2e-3)])
    z=np.concatenate([zc-u[::-1],[zc],zc+u])
    w=np.ones_like(z); t=np.abs(z-zc)>0.7*Y; w[t]=0.5*(1+np.cos(np.pi*(np.abs(z[t]-zc)-0.7*Y)/(0.3*Y)))
    m=np.sqrt(rs**2+(z-zs)**2); l=np.sqrt(rr**2+(z-zr)**2)
    eta=np.arccosh(np.maximum((m*l+(z-zs)*(z-zr))/(rs*rr),1.0))
    beta=sum(np.sin(nu*phi)/(np.cosh(nu*eta)-np.cos(nu*phi)) for phi in (np.pi+ps+pl,np.pi+ps-pl,np.pi-ps+pl,np.pi-ps-pl))
    fz=beta*w/(m*l); d=m+l
    out=np.array([np.trapezoid(fz*np.exp(-1j*kk*d),z) for kk in k])
    return -(nu/(4*np.pi))*out
cases=[]
rng=np.random.default_rng(1)
geoms=[]
for n in (2.0,1.5):
    for ps_deg in ((20,60,100,160,200,300,340) if n==2 else (20,60,120,200,250)):
        for pl_deg in ((15,50,90,150,210,250,330) if n==2 else (15,45,110,180,240)):
            ps,pl=np.radians(ps_deg),np.radians(pl_deg)
            # avoid shadow / reflection boundaries (singular BTM apex)
            if min(abs(abs(pl-ps)-np.pi),abs((pl+ps)-np.pi),abs((pl+ps)-(2*n-1)*np.pi))<np.radians(4): continue
            geoms.append((n,ps,pl))
sel=[geoms[i] for i in rng.choice(len(geoms),24,replace=False)]
for i,(n,ps,pl) in enumerate(sel):
    rs,rr=float(rng.uniform(0.5,4)),float(rng.uniform(0.5,4)); zs=0.0; zr=float(rng.choice([0.0,rng.uniform(-2,2)]))
    zc=zs+(zr-zs)*rs/(rs+rr); r1=np.hypot(rs,zc-zs); r2=np.hypot(rr,zr-zc); sinb=rs/r1
    btm_db=[];utd_db=[]
    for fc in FC:
        f=np.geomspace(fc/np.sqrt(2),fc*np.sqrt(2),24); k=2*np.pi*f/C
        pd=btm_wedge(ps,pl,rs,rr,zs,zr,n,k)
        btm_db.append(10*np.log10(np.mean(np.abs(pd)**2))+20*np.log10(r1+r2))
        A=utd_A(ps,pl,n,r1,r2,sinb,k); utd_db.append(10*np.log10(np.mean(np.abs(A)**2)))
    lit=abs(pl-ps)<np.pi
    cases.append(dict(n=n,phi_s=ps,phi_l=pl,rs=rs,rr=rr,dz=zr-zs,lit=bool(lit),btm_db=[round(x,3) for x in btm_db]))
    print(f"n={n} ps={np.degrees(ps):5.0f} pl={np.degrees(pl):5.0f} rs={rs:.2f} rr={rr:.2f} dz={zr:+.2f} {'lit' if lit else 'sh '} utd-btm:",np.round(np.array(utd_db)-btm_db,2),flush=True)
json.dump(dict(source="BTM (Svensson et al. 1999) line integral, rigid wedge, c=343.0, band rms over 24 log-spaced freqs per octave of p_d*(r1+r2); generated by scratch btm/fixtures.py",cases=cases),open('core/testdata/wedge_btm.json','w'),indent=1)
